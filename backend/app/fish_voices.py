# Fast lookups: by ID ("preset_fish_<hex>"), by reference ID (<hex>), and by key (slug)
FISH_VOICES_BY_ID: dict[str, FishVoiceProfile] = {}
for _voice in FISH_VOICES:
    FISH_VOICES_BY_ID[_voice["id"]] = _voice
    FISH_VOICES_BY_ID[_voice["reference_id"]] = _voice
    FISH_VOICES_BY_ID[_voice["key"]] = _voice

DEFAULT_FISH_VOICE_ID = "706b83690d4048b6a66f344c113c09cd"  # shakir 1
DEFAULT_FISH_VOICE_KEY = "shakir_1"

# All recognized keys for API validation
ALL_FISH_VOICE_KEYS: tuple[str, ...] = tuple(
    list({_voice["key"] for _voice in FISH_VOICES} |
         {_voice["id"] for _voice in FISH_VOICES} |
         {_voice["reference_id"] for _voice in FISH_VOICES})
)


def get_fish_voice(key_or_id: str | None) -> FishVoiceProfile | None:
    """Lookup a fish voice by preset id, reference id, or slug key."""
    if not key_or_id:
        return FISH_VOICES_BY_ID.get(DEFAULT_FISH_VOICE_ID)
    cleaned = key_or_id.strip()
    return FISH_VOICES_BY_ID.get(cleaned)


def resolve_fish_reference_id(key_or_id: str | None) -> str:
    """Resolve any input voice identifier to the 32-character hex Fish reference ID."""
    if not key_or_id:
        return DEFAULT_FISH_VOICE_ID

    cleaned = key_or_id.strip()

    # 1. Direct 32-char hex match
    if re.fullmatch(r"[0-9a-fA-F]{32}", cleaned):
        return cleaned

    # 2. Preset id prefix stripped match
    if cleaned.startswith("preset_fish_"):
        candidate = cleaned[len("preset_fish_"):]
        if re.fullmatch(r"[0-9a-fA-F]{32}", candidate):
            return candidate

    # 3. Catalog lookup
    match = FISH_VOICES_BY_ID.get(cleaned)
    if match:
        return match["reference_id"]

    return DEFAULT_FISH_VOICE_ID
